"""Provision once and encrypt owner handoff to an ephemeral recipient public key."""

import argparse
import json
from pathlib import Path
import secrets

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding, rsa

from bootstrap_collector import bootstrap


def provision(directory: Path, recipient_file: Path, envelope: Path):
    if directory.exists() or envelope.exists():
        raise ValueError("provisioning already exists; never regenerate credentials")
    recipient = serialization.load_pem_public_key(recipient_file.read_bytes())
    if not isinstance(recipient, rsa.RSAPublicKey) or recipient.key_size < 3072:
        raise ValueError("handoff requires a 3072-bit or stronger RSA recipient")
    password = secrets.token_urlsafe(32)
    bootstrap(directory, password)
    # Read only the HA credential just generated by this invocation, never an
    # existing deployment's credentials. No plaintext goes to stdout or SSH input.
    data = json.dumps({"admin_password": password,
        "mqtt_username": "homeassistant",
        "mqtt_password": (directory / "ha-password").read_text()}).encode()
    encrypted = recipient.encrypt(data, padding.OAEP(mgf=padding.MGF1(hashes.SHA256()),
        algorithm=hashes.SHA256(), label=b"collector-owner-handoff-v1"))
    with envelope.open("xb") as output:
        output.write(encrypted)
    envelope.chmod(0o600)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", required=True, type=Path)
    parser.add_argument("--recipient", required=True, type=Path)
    parser.add_argument("--envelope", required=True, type=Path)
    args = parser.parse_args()
    provision(args.directory, args.recipient, args.envelope)
    print("private_provisioning_created")
